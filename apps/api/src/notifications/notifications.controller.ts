import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  Param,
  Patch,
  Post,
  Put,
  UseGuards,
} from '@nestjs/common';
import { ApiBearerAuth, ApiOperation, ApiTags } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsBoolean,
  IsEnum,
  IsOptional,
  IsString,
  Length,
  MaxLength,
  ValidateNested,
} from 'class-validator';
import { NotificationCategory } from '@prisma/client';
import { AppAuthGuard } from '../common/guards/auth.guard';
import { CurrentUser } from '../common/decorators/current-user.decorator';
import type { AuthenticatedUser } from '../common/decorators/current-user.decorator';
import { NotificationsService } from './notifications.service';

class RegisterDeviceDto {
  /** Stable install identifier generated by the client. */
  @IsString()
  @Length(6, 128)
  deviceId!: string;

  @IsString()
  @Length(10, 4096)
  fcmToken!: string;

  @IsEnum(['IOS', 'ANDROID', 'WEB', 'ADMIN'])
  platform!: 'IOS' | 'ANDROID' | 'WEB' | 'ADMIN';

  @IsOptional()
  @IsString()
  @MaxLength(32)
  appVersion?: string;

  @IsOptional()
  @IsString()
  @MaxLength(16)
  locale?: string;
}

class PushNotificationPreferenceDto {
  @IsEnum(NotificationCategory)
  category!: NotificationCategory;

  @IsBoolean()
  push!: boolean;
}

class UpdatePushNotificationPreferencesDto {
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(10)
  @ValidateNested({ each: true })
  @Type(() => PushNotificationPreferenceDto)
  preferences!: PushNotificationPreferenceDto[];
}

@ApiTags('Notifications')
@ApiBearerAuth()
@Controller('notifications')
@UseGuards(AppAuthGuard)
export class NotificationsController {
  constructor(private readonly notifications: NotificationsService) {}

  @Get('my')
  @ApiOperation({ summary: 'List notifications for the current user' })
  listMine(@CurrentUser() current: AuthenticatedUser) {
    return this.notifications.listForUser(current.userId);
  }

  @Patch('my/read-all')
  @ApiOperation({ summary: 'Mark all notifications as read' })
  markAllRead(@CurrentUser() current: AuthenticatedUser) {
    return this.notifications.markAllRead(current.userId);
  }

  @Patch(':id/read')
  @ApiOperation({ summary: 'Mark a notification as read' })
  markRead(@CurrentUser() current: AuthenticatedUser, @Param('id') id: string) {
    return this.notifications.markRead(current.userId, id);
  }

  @Post('devices')
  @HttpCode(201)
  @ApiOperation({
    summary: 'Register or refresh a push device (specs 11/14)',
  })
  registerDevice(
    @CurrentUser() current: AuthenticatedUser,
    @Body() dto: RegisterDeviceDto,
  ) {
    return this.notifications.registerDevice(current.userId, dto);
  }

  @Get('devices')
  @ApiOperation({ summary: 'List my registered push devices' })
  listDevices(@CurrentUser() current: AuthenticatedUser) {
    return this.notifications.listDevices(current.userId);
  }

  @Delete('devices/:deviceId')
  @HttpCode(204)
  @ApiOperation({
    summary: 'Unregister a device — called on logout (spec 14)',
  })
  async removeDevice(
    @CurrentUser() current: AuthenticatedUser,
    @Param('deviceId') deviceId: string,
  ): Promise<void> {
    await this.notifications.removeDevice(current.userId, deviceId);
  }
}

/**
 * Spec 11/14 documented paths (`POST users/me/devices`,
 * `DELETE users/me/devices/:deviceId`). Alias of the `/notifications/devices`
 * routes so mobile hits the documented interface directly.
 */
@ApiTags('Notifications')
@ApiBearerAuth()
@Controller('users/me')
@UseGuards(AppAuthGuard)
export class UserDevicesController {
  constructor(private readonly notifications: NotificationsService) {}

  @Get('notification-preferences')
  @ApiOperation({
    summary: 'Get push preferences by notification category',
  })
  getNotificationPreferences(@CurrentUser() current: AuthenticatedUser) {
    return this.notifications.getPushPreferences(current.userId);
  }

  @Put('notification-preferences')
  @ApiOperation({
    summary: 'Update push preferences by notification category',
  })
  updateNotificationPreferences(
    @CurrentUser() current: AuthenticatedUser,
    @Body() dto: UpdatePushNotificationPreferencesDto,
  ) {
    return this.notifications.updatePushPreferences(
      current.userId,
      dto.preferences,
    );
  }

  @Post('devices')
  @HttpCode(201)
  @ApiOperation({
    summary: 'Register or refresh a push device (documented path)',
  })
  registerDevice(
    @CurrentUser() current: AuthenticatedUser,
    @Body() dto: RegisterDeviceDto,
  ) {
    return this.notifications.registerDevice(current.userId, dto);
  }

  @Get('devices')
  @ApiOperation({
    summary: 'List my registered push devices (documented path)',
  })
  listDevices(@CurrentUser() current: AuthenticatedUser) {
    return this.notifications.listDevices(current.userId);
  }

  @Delete('devices/:deviceId')
  @HttpCode(204)
  @ApiOperation({ summary: 'Unregister a device on logout (documented path)' })
  async removeDevice(
    @CurrentUser() current: AuthenticatedUser,
    @Param('deviceId') deviceId: string,
  ): Promise<void> {
    await this.notifications.removeDevice(current.userId, deviceId);
  }
}
